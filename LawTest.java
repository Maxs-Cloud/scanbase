package ru.scanbase;

/* Регламент (eu_cosmetics_law / trts_cosmetics_law) обязан перекрывать дозу:
   вещество из списка запрещённого — это «высокий» риск и «с ограничением»,
   а не «разрешено в малой дозе». Ограниченное в пределах нормы — средний,
   при превышении — «превышение» и высокий. Пустой список права не трогает.
   javac -cp android.jar:build/obj LawTest.java
   java  -cp android.jar:build/obj:. ru.scanbase.LawTest                       */
public class LawTest {

    static int fails = 0;
    static int total = 0;

    static MainActivity.Item item(String name, double pct, String[]... law) {
        MainActivity.Item item = new MainActivity.Item();
        item.name = name;
        item.status = "не найден";
        item.role = "—";
        item.risk = "неизвестно";
        item.catalog = true;
        item.pct = pct;
        for (String[] e : law) {
            item.law.add(e);
        }
        MainActivity.classify(item);
        return item;
    }

    static void check(String what, MainActivity.Item item, String wantStatus, String wantRisk) {
        total++;
        boolean ok = wantStatus.equals(item.status) && wantRisk.equals(item.risk);
        if (!ok) {
            fails++;
        }
        System.out.println((ok ? "ok   " : "FAIL ") + what + " -> " + item.status + ", " + item.risk
                + (ok ? "" : "  ожидали «" + wantStatus + ", " + wantRisk + "»"));
    }

    public static void main(String[] args) {
        /* Запрещённое: любой из трёх форматов пометки в колонке annex. */
        check("Annex II по-русски",
                item("Вещество А", 0.0d, new String[]{"EU", "II запрещено", "1339", ""}),
                "с ограничением", "высокий");
        check("Annex II латиницей (точное совпадение)",
                item("Вещество А", 0.0d, new String[]{"EU", "Ann II", "1339", ""}),
                "с ограничением", "высокий");
        check("ТР ТС Приложение 1",
                item("Вещество А", 0.0d, new String[]{"EAEU", "Прил 1", "1339", ""}),
                "с ограничением", "высокий");

        /* Запрет сильнее дозы: даже при крошечном проценте и указанной норме
           это тревога, а не «разрешено в малой дозе». */
        check("запрет перекрывает дозу",
                item("Вещество А", 0.01d, new String[]{"EU", "II запрещено", "1339", "2%"}),
                "с ограничением", "высокий");

        /* Запрет побеждает и тогда, когда рядом есть ограничивающая запись. */
        check("запрет побеждает ограничение рядом",
                item("Вещество А", 0.0d,
                        new String[]{"EU", "III ограничено", "1339", "0.03%"},
                        new String[]{"EAEU", "Прил 1", "1339", ""}),
                "с ограничением", "высокий");

        /* Ограниченное в пределах нормы — средний риск, статус «с ограничением». */
        check("в пределах нормы",
                item("Вещество Б", 0.02d, new String[]{"EU", "III ограничено", "4", "0.03%"}),
                "с ограничением", "средний");
        check("ровно на границе нормы",
                item("Вещество Б", 0.03d, new String[]{"EU", "III ограничено", "4", "0.03%"}),
                "с ограничением", "средний");
        check("норма не указана — считаем ограниченным",
                item("Вещество Б", 5.0d, new String[]{"EU", "III ограничено", "4", ""}),
                "с ограничением", "средний");
        check("норма с запятой",
                item("Вещество Б", 0.01d, new String[]{"EU", "III ограничено", "4", "0,03%"}),
                "с ограничением", "средний");

        /* Превышение нормы — высокий и отдельный статус. */
        check("превышение нормы",
                item("Вещество Б", 1.0d, new String[]{"EU", "III ограничено", "4", "0.03%"}),
                "превышение", "высокий");
        check("из нормы нескольких записей берётся минимальная",
                item("Вещество Б", 0.5d,
                        new String[]{"EU", "III ограничено", "4", "2%"},
                        new String[]{"EAEU", "Прил 2", "4", "0.3%"}),
                "превышение", "высокий");

        /* Пустой список права ничего не меняет: каталожный ингредиент — низкий. */
        check("без регламента риск низкий",
                item("Вещество В", 0.0d),
                "не найден", "низкий");

        /* Фиксация текущего поведения: точные латинские/русские метки регистрозависимы,
           «англ. строчными» и «расшифровка словами» в запрет не попадают. */
        check("«ann ii» строчными — не запрет (текущее поведение)",
                item("Вещество Г", 0.02d, new String[]{"EU", "ann ii", "1339", "0.03%"}),
                "с ограничением", "средний");
        check("«запрещённые вещества» словами — не запрет по точному слову, но содержит «запрещ»",
                item("Вещество Г", 0.0d, new String[]{"EU", "список запрещённых веществ", "1339", ""}),
                "с ограничением", "высокий");

        System.out.println(fails == 0 ? "LawTest: всё зелёное (" + total + ")"
                : "LawTest: ПРОВАЛОВ " + fails + " из " + total);
        if (fails > 0) {
            System.exit(1);
        }
    }
}
