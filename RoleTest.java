package ru.scanbase;

/* Роль и риск типовых компонентов. Проверяет в первую очередь то, что база не
   пугает без причины: вода — растворитель с низким риском, а не «вредный»,
   безобидный цетиловый спирт не прыгает в средний риск, а реальные ограничители
   (изотиазолиноны, доноры формальдегида) остаются высокими.
   javac -cp android.jar:build/obj RoleTest.java
   java  -cp android.jar:build/obj:. ru.scanbase.RoleTest                        */
public class RoleTest {

    static int fails = 0;
    static int total = 0;

    static void check(String what, String name, boolean catalog, String wantRole, String wantRisk) {
        total++;
        MainActivity.Item item = new MainActivity.Item();
        item.name = name;
        item.status = "не найден";
        item.role = "—";
        item.risk = "неизвестно";
        item.catalog = catalog;
        MainActivity.classify(item);
        boolean ok = wantRole.equals(item.role) && wantRisk.equals(item.risk);
        if (!ok) {
            fails++;
        }
        System.out.println((ok ? "ok   " : "FAIL ") + name + " -> " + item.role + ", " + item.risk
                + (ok ? "" : "  ожидали «" + wantRole + ", " + wantRisk + "»"));
    }

    public static void main(String[] args) {
        check("вода по-русски не вредная", "Вода", true, "растворитель", "низкий");
        check("aqua", "Aqua", true, "растворитель", "низкий");
        check("вода дистиллированная", "вода дистиллированная", true, "растворитель", "низкий");
        check("глицерин", "Глицерин", true, "увлажнение", "низкий");
        check("пантенол", "Пантенол", true, "увлажнение", "низкий");
        check("гиалуроновая кислота", "Гиалуроновая кислота", true, "актив", "низкий");
        check("ниацинамид", "Ниацинамид", true, "актив", "низкий");
        check("масло ши", "Butyrospermum Parkii Butter", true, "смягчение", "низкий");
        check("жирный спирт — не растворитель", "Cetyl Alcohol", true, "смягчение", "низкий");
        check("жирный спирт по-русски", "цетиловый спирт", true, "смягчение", "низкий");
        check("стеариловый спирт по-русски", "стеариловый спирт", true, "смягчение", "низкий");
        check("ПАВ латиницей", "Sodium Lauryl Sulfate", true, "ПАВ", "средний");
        check("ПАВ по-русски", "лаурет сульфат натрия", true, "ПАВ", "средний");
        check("мягкий глюкозид", "коко глюкозид", true, "ПАВ", "средний");
        check("мыло", "мыло хозяйственное", true, "ПАВ", "средний");
        check("консервант обычный", "феноксиэтанол", true, "консервант", "низкий");
        check("парабен — ограничитель, не яд", "метилпарабен", true, "консервант", "средний");
        check("отдушка", "отдушка", true, "отдушка", "средний");
        check("аллерген отдушки", "лимонен", true, "отдушка", "средний");
        check("изотиазолинон — высокий", "метилизотиазолинон", true, "консервант", "высокий");
        check("донор формальдегида — высокий", "имидазолидинил мочевина", true, "консервант", "высокий");
        check("спирт денат — средний", "спирт денат", true, "растворитель", "средний");
        check("материал кожи", "кожа", false, "кожа", "низкий");
        check("материал полиэстера", "полиэстер", false, "синтетика", "низкий");
        check("бытовая химия: щёлочь", "гидроксид натрия", false, "щёлочь", "высокий");
        check("ЭДТК по-старому", "динатрия ЭДТК", false, "комплексообразователь", "средний");
        check("ЭДТА по-русски с «а»", "динатрия ЭДТА", false, "комплексообразователь", "средний");
        check("тетранатрия ЭДТА", "тетранатрия ЭДТА", false, "комплексообразователь", "средний");
        check("тринатрия ЭДТА", "тринатрия ЭДТА", false, "комплексообразователь", "средний");
        check("соль ЭДТА из живого разбора", "соль ЭДТА", false, "комплексообразователь", "средний");
        check("ЭДТА латиницей", "Tetrasodium EDTA", false, "комплексообразователь", "средний");
        check("нитрилотриуксусная кислота", "нитрилотриуксусная кислота", false,
                "комплексообразователь", "средний");
        check("краситель по-русски", "краситель", false, "краситель", "низкий");
        check("краситель латиницей", "Colorant", false, "краситель", "низкий");
        check("пигмент", "пигмент", false, "краситель", "низкий");
        check("ci-номер красителя из каталога", "CI 77491", true, "краситель", "средний");
        check("неизвестное не выдумываем", "флавогликопротеид", false, "не распознан", "неизвестно");

        System.out.println("\nпроверок " + total + ", падений " + fails);
        if (fails > 0) {
            System.exit(1);
        }
    }
}
